export function readProjects(projectList = projects) {
  return [...projectList];
}

export function readProject(slug, projectList = projects) {
  return projectList.find((project) => project.slug === slug) ?? null;
}

export function createProject(projectList, project) {
  if (!project || typeof project.slug !== "string" || !project.slug.trim()) {
    throw new Error("A project must have a non-empty slug.");
  }
  if (projectList.some((item) => item.slug === project.slug)) {
    throw new Error(`A project with slug "${project.slug}" already exists.`);
  }
  return [...projectList, project];
}

export function updateProject(projectList, slug, updates) {
  const projectIndex = projectList.findIndex(
    (project) => project.slug === slug,
  );
  if (projectIndex === -1) {
    throw new Error(`Project "${slug}" was not found.`);
  }
  if (!updates || typeof updates !== "object" || Array.isArray(updates)) {
    throw new Error("Project updates must be an object.");
  }

  const updatedProject = { ...projectList[projectIndex], ...updates };
  if (typeof updatedProject.slug !== "string" || !updatedProject.slug.trim()) {
    throw new Error("A project must have a non-empty slug.");
  }
  if (
    updatedProject.slug !== slug &&
    projectList.some((project) => project.slug === updatedProject.slug)
  ) {
    throw new Error(
      `A project with slug "${updatedProject.slug}" already exists.`,
    );
  }

  return projectList.map((project, index) =>
    index === projectIndex ? updatedProject : project,
  );
}

export function deleteProject(projectList, slug) {
  if (!projectList.some((project) => project.slug === slug)) {
    throw new Error(`Project "${slug}" was not found.`);
  }
  return projectList.filter((project) => project.slug !== slug);
}
